# Program to calculate acceleration of a car

# Input values
v_initial = 0      # initial velocity in m/s
v_final = 10       # final velocity in m/s
time = 20          # time in seconds

# Calculate acceleration
acceleration = (v_final - v_initial) / time

# Display the result
print("Initial Velocity =", v_initial, "m/s")
print("Final Velocity =", v_final, "m/s")
print("Time Taken =", time, "seconds")
print("Acceleration of the car =", acceleration, "m/s²")
